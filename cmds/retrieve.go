func DataGenerator(LangListFunc fn, GeneratedFuncName string) string {
	// FIXME: This is jank as hell, I need to refactor this later
	SL := LangListFunc("sl")
	TL := LangListFunc("tl")
	var formattedSL string
	var formattedTL string
	for _, i := range SL {
		formattedSL = formattedSL + `{ Id: "` + i.Id + `", Name: "` + i.Name + `",},`
	}
	for _, i := range TL {
		formattedTL = formattedTL + `{ Id: "` + i.Id + `", Name: "` + i.Name + `",},`
	}
	data := `
	func ` + GeneratedFuncName + `(listType string) []List {
		ListDataSL := []List{`
	data = data + formattedSL
	data = data + `}
		ListDataTL := []List{`
	data = data + formattedTL
	data = data + `}
		if listType == "sl" {
			return ListDataSL
		} else {
			return ListDataTL
		}
	}`
	return data
}

func LangListGoogle(listType string) []List {
	UserAgent, ok := os.LookupEnv("MOZHI_USER_AGENT")
	if !ok {
		UserAgent = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/110.0.0.0 Safari/537.36"
	}
	sc := colly.NewCollector(colly.AllowedDomains("translate.google.com"), colly.UserAgent(UserAgent))
	var ListData []List
	sc.OnHTML("body", func(e *colly.HTMLElement) {
		e.ForEach("div.language-item", func(i int, el *colly.HTMLElement) {
			var ListInfo List
			ListInfo.Name = el.ChildText("a")
			if listType == "tl" {
				ListInfo.Id = strings.TrimPrefix(strings.TrimSuffix(el.ChildAttr("a", "href"), "&hl=en-US"), "./m?sl=en&tl=")
			} else {
				ListInfo.Id = strings.TrimPrefix(strings.TrimSuffix(el.ChildAttr("a", "href"), "&tl=en&hl=en-US"), "./m?sl=")
			}
			ListData = append(ListData, ListInfo)
		})
	})
	url := "https://translate.google.com/m?sl=en&tl=en&hl=en-US&mui=" + listType
	sc.Visit(url)
	return ListData
}
